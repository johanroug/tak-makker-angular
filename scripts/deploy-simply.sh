#!/usr/bin/env bash
set -euo pipefail

# Run only after a successful build. Secrets belong to the deployment job,
# never to npm install/build. The target is fixed to this account's public_html.
: "${SIMPLY_SSH_USER:?Set SIMPLY_SSH_USER in GitHub environment simply-production}"
: "${SIMPLY_SSH_PRIVATE_KEY:?Set SIMPLY_SSH_PRIVATE_KEY in GitHub environment simply-production}"
: "${SIMPLY_SSH_KNOWN_HOSTS:?Set SIMPLY_SSH_KNOWN_HOSTS in GitHub environment simply-production}"
if [[ ! "$SIMPLY_SSH_USER" =~ ^[a-zA-Z0-9._-]+$ ]]; then
  echo 'Unexpected SSH username format.' >&2
  exit 1
fi

build_directory='dist/hovedet-paa-soemmet-angular/browser'
for required_file in index.html index.csr.html 404.html .htaccess; do
  [[ -s "$build_directory/$required_file" ]] || { echo "Missing build file: $required_file" >&2; exit 1; }
done
public_routes=$(tr -d '\r' < "$build_directory/.htaccess" | sed -n '/^# BEGIN Angular public routes$/,/^# END Angular public routes$/p')
[[ "$public_routes" == *'RewriteRule '* ]] || { echo 'Missing public routing block in build .htaccess' >&2; exit 1; }

ssh_directory=$(mktemp -d)
trap 'rm -f "$ssh_directory/key" "$ssh_directory/known_hosts"; rmdir "$ssh_directory"' EXIT
chmod 700 "$ssh_directory"
printf '%s\n' "$SIMPLY_SSH_PRIVATE_KEY" > "$ssh_directory/key"
printf '%s\n' "$SIMPLY_SSH_KNOWN_HOSTS" > "$ssh_directory/known_hosts"
chmod 600 "$ssh_directory/key" "$ssh_directory/known_hosts"
unset SIMPLY_SSH_PRIVATE_KEY SIMPLY_SSH_KNOWN_HOSTS

ssh_options=(-i "$ssh_directory/key" -o "UserKnownHostsFile=$ssh_directory/known_hosts"
  -o StrictHostKeyChecking=yes -o BatchMode=yes -o IdentitiesOnly=yes -o ConnectTimeout=20)
remote="$SIMPLY_SSH_USER@ssh.simply.com"

# Preserve the tested server configuration and Simply-managed HTTPS rules.
# Abort on a new/misconfigured account rather than deploying to an arbitrary folder.
ssh "${ssh_options[@]}" "$remote" 'test -d public_html && test -f public_html/.htaccess && test -f public_html/index.html && command -v rsync >/dev/null'

# rsync needs the SSH options as one string; temporary paths are generated by
# mktemp and contain no spaces on the GitHub-hosted Linux runner.
rsync_shell="ssh -i $ssh_directory/key -o UserKnownHostsFile=$ssh_directory/known_hosts -o StrictHostKeyChecking=yes -o BatchMode=yes -o IdentitiesOnly=yes -o ConnectTimeout=20"

# Upload resources first. Old hashes remain so tabs opened before deployment
# can still fetch their lazy chunks. No --delete and no changes to .well-known.
rsync -az --delay-updates --exclude='.htaccess' --exclude='*.html' \
  -e "$rsync_shell" "$build_directory/" "$remote:public_html/"

# Activate HTML only after the referenced resources are all in place.
# Files are replaced by rename when transfer completes; the entire site is
# not switched atomically. The workflow serializes deployments.
rsync -az --delay-updates --include='*/' --include='*.html' --exclude='*' \
  -e "$rsync_shell" "$build_directory/" "$remote:public_html/"

# Synchronize public routes after their HTML exists, retaining Simply HTTPS rules.
# Existing unmarked legacy routes may remain; the managed block covers new pages.
printf '%s\n' "$public_routes" | ssh "${ssh_options[@]}" "$remote" 'set -eu
  routing_block=$(mktemp)
  routing_file=$(mktemp public_html/.htaccess.XXXXXX)
  trap '\''rm -f "$routing_block" "$routing_file"'\'' EXIT
  cat > "$routing_block"
  grep -Fqx "# BEGIN Angular public routes" "$routing_block"
  grep -Fqx "# END Angular public routes" "$routing_block"
  tr -d "\r" < public_html/.htaccess | awk '\''
    $0 == "# BEGIN Angular public routes" { managed = 1; next }
    $0 == "# END Angular public routes" { managed = 0; next }
    !managed { print }
    END { if (managed) exit 1 }
  '\'' > "$routing_file"
  printf "\n" >> "$routing_file"
  cat "$routing_block" >> "$routing_file"
  if ! grep -Fq "reset-password|customers|projects" public_html/.htaccess; then
    grep -Fq "reset-password|projects" public_html/.htaccess
    sed -i "s/reset-password|projects/reset-password|customers|projects/" "$routing_file"
  fi
  chmod --reference=public_html/.htaccess "$routing_file"
  mv "$routing_file" public_html/.htaccess'

echo 'Website uploaded. Public routes synchronized; Simply HTTPS rules, certificates and old hashed assets preserved.'
